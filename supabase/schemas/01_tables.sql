--
-- What a team is expected to sell, per period.
--
-- A separate table rather than a column on `teams`: a budget without a period
-- cannot answer "how did we do in Q3", and overwriting the number to set the
-- next target would destroy the only record of the previous one.
--
-- The exclusion constraint is the load-bearing one. Two overlapping periods for
-- the same team would make the dashboard pick a vigente budget arbitrarily,
-- which shows up as a number that changes between page loads.
--
create table public.team_budgets (
    id           bigint generated by default as identity primary key,
    team_id      bigint not null references public.teams(id) on delete cascade,
    period_start date not null,
    period_end   date not null,
    amount       numeric(14,2) not null check (amount >= 0),
    created_at   timestamp with time zone not null default now(),
    constraint team_budgets_period_order check (period_end > period_start),
    constraint team_budgets_no_overlap exclude using gist (
        team_id with =,
        daterange(period_start, period_end, '[]') with &&
    ),
    -- Foreign-key target for `team_member_budgets`, same reason as on
    -- `team_members` above.
    constraint team_budgets_id_team_id_key unique (id, team_id)
);

--
-- What each member of a team is expected to sell out of the team's target.
--
-- Keyed on the BUDGET, not on the team: an allocation with no period is the
-- mistake `team_budgets` exists to avoid — it would follow the team into the
-- next period and silently restate what was promised for the last one. Hanging
-- it off `team_budgets.id` makes "open a new period" mean "start from a blank
-- allocation", which is the honest default.
--
-- Keyed on the MEMBERSHIP rather than on the person: somebody removed from the
-- team carries no quota in it, so the roster quotas always sum to the team's
-- allocated total and the breakdown reconciles with the figure it sits under.
--
-- The two composite foreign keys are the load-bearing part. With plain
-- `references team_budgets(id)` / `references team_members(id)`, team A's
-- budget paired with team B's member is accepted, and that row is invisible in
-- every screen: it sums into one team's allocated total while the roster it
-- should appear in never shows it.
--
-- The sum is deliberately NOT constrained to the team budget. Reallocating
-- between two members is two writes, and an invariant enforced per row would
-- reject the first one purely for being first. Over- and under-allocation are
-- reported by the UI instead, which is also the only place that can say by how
-- much.
--
create table public.team_member_budgets (
    id             bigint generated by default as identity primary key,
    team_id        bigint not null,
    budget_id      bigint not null,
    team_member_id bigint not null,
    amount         numeric(14,2) not null check (amount >= 0),
    created_at     timestamp with time zone not null default now(),
    unique (budget_id, team_member_id),
    foreign key (budget_id, team_id)
        references public.team_budgets (id, team_id) on delete cascade,
    foreign key (team_member_id, team_id)
        references public.team_members (id, team_id) on delete cascade
);

-- "What is this person's quota", asked by the member drill-down. The unique
-- index above leads with `budget_id` and cannot serve it.
create index team_member_budgets_team_member_id_idx
    on public.team_member_budgets (team_member_id);

