);

--
-- Attachments (§3.2, §8.2)
--
-- One table for both task-level and comment-level files: a comment attachment
-- is a task attachment with `comment_id` set. Two tables would mean two upload
-- flows, two policies and two counters for the same thing.
--
-- The row is metadata; the bytes live in the private `task-attachments`
-- storage bucket under `<task_id>/…`, which is what lets the storage policy
-- gate a download on `can_see_task()` (§17.3). The public `attachments` bucket
-- used by notes cannot do that: a public bucket serves any object to anyone
-- holding the URL, signed in or not.
--
create table public.task_attachments (
    id           bigint generated by default as identity primary key,
    task_id      bigint not null references public.tasks(id) on delete restrict,
    -- Null for a task-level attachment; set when the file hangs off a comment.
    comment_id   bigint references public.task_comments(id) on delete restrict,

    storage_path text not null,          -- '<task_id>/<random>.<ext>' in the bucket
    file_name    text not null,          -- what the user uploaded, for display
    mime_type    text,
    size_bytes   bigint,
    -- SHA-256 of the bytes, computed at upload time. Recorded rather than used:
    -- it is the one piece of metadata that cannot be recovered afterwards if a
    -- retention job has already moved the object.
    checksum     text,

    uploaded_by  bigint not null references public.sales(id),
    uploaded_at  timestamp with time zone not null default now(),
    -- Soft delete, like everything else in this module: the history references
    -- the attachment by id and must keep resolving.
    deleted_at   timestamp with time zone,
    deleted_by   bigint references public.sales(id),

    constraint task_attachments_file_name_not_blank check (btrim(file_name) <> ''),
    constraint task_attachments_path_not_blank check (btrim(storage_path) <> ''),
    constraint task_attachments_size_not_negative
        check (size_bytes is null or size_bytes >= 0)
);

-- "The files on this task" — the only query the detail panel makes.
create index task_attachments_task
    on public.task_attachments (task_id, uploaded_at)
    where deleted_at is null;

-- "The files on this comment", rendered under each message in the thread.
create index task_attachments_comment
    on public.task_attachments (comment_id, uploaded_at)
    where deleted_at is null and comment_id is not null;

-- One live row per stored object: a retry that re-registers the same upload
-- would double the counter and show the file twice.
create unique index task_attachments_path_unique
    on public.task_attachments (storage_path)
    where deleted_at is null;

--
-- Checklists (§11)
--
-- A checklist item is a step of somebody else's work item, not a work item of
-- its own: no status machine, no comments, never in "my tasks". When a step
-- needs its own owner it should become a sub-task instead (§11.1).
--

create table public.task_checklist_items (
    id          bigint generated by default as identity primary key,
    task_id     bigint not null references public.tasks(id) on delete restrict,
    label       text not null,
    -- Fractional ranking: inserting between 1.0 and 2.0 writes 1.5, so a drag
    -- and drop is one row update instead of renumbering the whole list.
    position    numeric not null,
    is_done     boolean not null default false,
    done_at     timestamp with time zone,
    done_by     bigint references public.sales(id),
    due_at      timestamp with time zone,
    assignee_id bigint references public.sales(id),
    created_by  bigint not null references public.sales(id),
    created_at  timestamp with time zone not null default now(),
    deleted_at  timestamp with time zone,

    constraint task_checklist_items_label_not_blank check (btrim(label) <> ''),
    -- "Done" without who and when is the exact hole this module exists to fix.
    constraint checklist_done_consistency
        check ((is_done = false and done_at is null and done_by is null)
            or (is_done = true and done_at is not null and done_by is not null))
);

create index task_checklist_items_task
    on public.task_checklist_items (task_id, position)
    where deleted_at is null;

--
-- Dependencies (§10)
--
-- Edges are directed and stored ONCE; the inverse is derived ("A blocks B"
-- means "B is blocked by A"). Storing both directions is the classic source of
-- inconsistent graphs.
--

create type public.task_dependency_kind as enum
    ('blocks', 'parent', 'related', 'duplicates');

create table public.task_dependencies (
    id             bigint generated by default as identity primary key,
    source_task_id bigint not null references public.tasks(id) on delete restrict,
    target_task_id bigint not null references public.tasks(id) on delete restrict,
    kind           public.task_dependency_kind not null,
    created_by     bigint not null references public.sales(id),
    created_at     timestamp with time zone not null default now(),
    removed_at     timestamp with time zone,
    removed_by     bigint references public.sales(id),

    constraint no_self_dependency check (source_task_id <> target_task_id)
);

create unique index task_dependencies_unique_active
    on public.task_dependencies (source_task_id, target_task_id, kind)
    where removed_at is null;

-- "What blocks me?" — walked on every completion to release dependents.
create index task_dependencies_reverse
    on public.task_dependencies (target_task_id, kind)
    where removed_at is null;

--
-- Reminders (§9)
--
-- Two tables, because a rule is edited while a delivery is a fact. Editing
-- "remind me a day before" must not rewrite the record of the ping that already
-- went out last Tuesday — that is the same append-only reasoning as
-- `task_events`, applied to notifications.
--

create type public.reminder_channel as enum
    ('in_app', 'email', 'push', 'whatsapp', 'sms', 'webhook');

create table public.task_reminders (
    id             bigint generated by default as identity primary key,
    task_id        bigint not null references public.tasks(id) on delete restrict,
    created_by     bigint not null references public.sales(id),
    created_at     timestamp with time zone not null default now(),

    -- WHEN
    schedule_kind  text not null check (schedule_kind in
                     ('absolute', 'relative_before_due', 'relative_after_due', 'recurring')),
    absolute_at    timestamp with time zone,
    -- For relative_*: 60 = one hour before (or after) the due date.
    offset_minutes integer,
    -- RFC 5545 rather than a bespoke format: it is what every calendar client
    -- already speaks, which makes iCal export in Phase 3 free (§9.2).
    rrule          text,
    timezone       text not null default 'UTC',
    until_at       timestamp with time zone,
    max_occurrences integer,

    -- WHO / HOW
    channels       public.reminder_channel[] not null default '{in_app}',
    recipients     text not null default 'owner'
                   check (recipients in ('owner', 'assignees', 'watchers', 'all', 'custom')),
    custom_recipients bigint[],
    message_template text,

    -- STATE
    is_active      boolean not null default true,
    -- Materialized for the scheduler: the dispatcher must never recompute a
    -- schedule for rows it is not going to fire.
    next_fire_at   timestamp with time zone,
    fired_count    integer not null default 0,
    stop_on_complete boolean not null default true,

    -- Each schedule kind needs exactly the field that defines it.
    constraint task_reminders_schedule_shape check (
        (schedule_kind = 'absolute' and absolute_at is not null)
        or (schedule_kind in ('relative_before_due', 'relative_after_due')
            and offset_minutes is not null and offset_minutes >= 0)
        or (schedule_kind = 'recurring' and btrim(coalesce(rrule, '')) <> '')
    ),
    constraint task_reminders_channels_not_empty
        check (array_length(channels, 1) >= 1),
    constraint task_reminders_custom_recipients check (
        recipients <> 'custom'
        or coalesce(array_length(custom_recipients, 1), 0) >= 1
    )
);

-- The scheduler's ONLY query. Partial, so it stays the size of the pending
-- work rather than the size of the reminder history.
create index task_reminders_due
    on public.task_reminders (next_fire_at)
    where is_active and next_fire_at is not null;

create index task_reminders_task
    on public.task_reminders (task_id)
    where is_active;

--
-- The outbox. One row per delivery attempt per recipient per channel, so a
-- reminder that was never delivered is visible AS SUCH (O6) instead of being
-- indistinguishable from one nobody acted on.
--
create table public.task_notifications (
    id            bigint generated by default as identity primary key,
    reminder_id   bigint references public.task_reminders(id),
    task_id       bigint not null references public.tasks(id) on delete restrict,
    recipient_id  bigint not null references public.sales(id),
    channel       public.reminder_channel not null,
    scheduled_for timestamp with time zone not null,
    sent_at       timestamp with time zone,
    delivered_at  timestamp with time zone,
    read_at       timestamp with time zone,
    acknowledged_at timestamp with time zone,
    title         text,
    body          text,
    status        text not null default 'queued'
                  check (status in ('queued', 'sending', 'sent', 'delivered',
                                    'failed', 'bounced', 'skipped', 'canceled')),
    attempt       smallint not null default 0,
    error         text,
    provider_message_id text,
    -- Idempotency: `reminder:occurrence:recipient:channel`. A replayed
    -- dispatch is a no-op instead of a second ping.
    dedupe_key    text unique,
    created_at    timestamp with time zone not null default now()
);

-- The worker's claim query.
create index task_notifications_outbox
    on public.task_notifications (status, scheduled_for)
    where status in ('queued', 'sending');

-- "My unread in-app notifications" — the bell badge, on every page load.
create index task_notifications_inbox
    on public.task_notifications (recipient_id, created_at desc)
    where channel = 'in_app' and read_at is null;

create index task_notifications_task
    on public.task_notifications (task_id, created_at desc);

--
-- Anti-fatigue preferences for reminders (§9.5)
--
-- "A reminder system without throttling is uninstalled within a week." One row
-- per user; absent means the defaults, so nobody needs backfilling.
--
create table public.notification_preferences (
    id          bigint generated by default as identity primary key,
    sales_id    bigint not null unique references public.sales(id) on delete cascade,

    -- Quiet hours are expressed in the user's own timezone; storing them as
    -- `time` plus a zone is what makes "no pings before 08:00" mean the same
    -- thing in Bogota and in Madrid.
    timezone    text not null default 'UTC',
    quiet_hours_start time,
    quiet_hours_end   time,

    -- Digest: one message at a fixed hour instead of N pings through the day.
    digest_mode boolean not null default false,
    digest_at   time not null default '08:00',

    -- Per-channel opt-out. Per-EVENT-TYPE preferences are deliberately not
    -- modelled yet: every row in the outbox comes from a reminder today, so a
    -- second axis would have exactly one value to key on (YAGNI). Add it when
    -- automations start writing notifications (Phase 3).
    muted_channels public.reminder_channel[] not null default '{}',

    -- Hard ceiling on deliveries per rolling hour, enforced at claim time.
    max_per_hour integer not null default 20 check (max_per_hour > 0),

    -- "Same task, several rules fired" collapses inside this window.
    dedupe_window_minutes integer not null default 60
        check (dedupe_window_minutes >= 0),

    created_at  timestamp with time zone not null default now(),
    updated_at  timestamp with time zone not null default now()
);

create index notification_preferences_sales_id_idx
    on public.notification_preferences (sales_id);

