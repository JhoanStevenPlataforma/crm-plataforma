-- Indexes on foreign keys
--

create index contact_notes_contact_id_idx on public.contact_notes using btree (contact_id);
create index contacts_company_id_idx on public.contacts using btree (company_id);
create index deal_notes_deal_id_idx on public.deal_notes using btree (deal_id);
create index deals_company_id_idx on public.deals using btree (company_id);

--
-- Ownership indexes
--
-- Every owner-scoped RLS policy filters on `sales_id`, and so do the
-- "only mine" list filters. Without these the policies degrade to a sequential
-- scan on every list query.
--
create index companies_sales_id_idx on public.companies using btree (sales_id);
create index contacts_sales_id_idx on public.contacts using btree (sales_id);
create index deals_sales_id_idx on public.deals using btree (sales_id);
create index contact_notes_sales_id_idx on public.contact_notes using btree (sales_id);
create index deal_notes_sales_id_idx on public.deal_notes using btree (sales_id);

-- tasks.contact_id had no index at all: it now carries both the contact detail
-- page lookup and the task RLS policy, which resolves ownership through the
-- parent contact. This is by far the most scanned index in the schema.
create index tasks_contact_id_idx on public.tasks using btree (contact_id);
-- The task list filters by owner and orders by due date.
create index tasks_sales_id_due_date_idx on public.tasks using btree (sales_id, due_date);

--
-- List ordering indexes
--
-- Every one of these backs an `order by ... limit n` that would otherwise
-- top-N heapsort the whole table on each page load. Partial where the list is
-- always filtered the same way.
--
create index contacts_last_seen_idx on public.contacts using btree (last_seen desc);
create index contact_notes_date_idx on public.contact_notes using btree (date desc);
create index deal_notes_date_idx on public.deal_notes using btree (date desc);
-- Backs `contacts_summary.nb_tasks`.
create index tasks_pending_contact_id_idx on public.tasks using btree (contact_id) where done_date is null;
-- Backs the "tasks due" lists, which never show completed tasks.
create index tasks_pending_due_date_idx on public.tasks using btree (due_date) where done_date is null;
-- Backs the deal kanban, which only ever lists non-archived deals.
create index deals_active_index_idx on public.deals using btree (index desc) where archived_at is null;

-- Leads: owner scoping (RLS + "only mine"), the default list ordering, and the
-- conversion pointers used by the contact/company/deal detail pages.
create index leads_sales_id_idx on public.leads using btree (sales_id);
create index leads_created_at_idx on public.leads using btree (created_at desc);
create index leads_company_id_idx on public.leads using btree (company_id);
create index leads_converted_contact_id_idx on public.leads using btree (converted_contact_id);
