--
-- Why a deal moved from one stage to the next.
--
-- The kanban used to write `deals.stage` and nothing else, so the board could
-- say a deal reached "proposal sent" but never why, when, or on whose call.
-- This is the append-only record of every transition: the reason typed at the
-- moment of the move, the files that justified it, and the person who did it.
--
-- Written by `public.deals_log_stage_change()` only, on any path that changes
-- the stage (kanban, edit form, import). A client cannot insert here, so the
-- history cannot be back-dated or invented -- see 05_policies.sql.
--
-- `attachments` mirrors `deal_notes.attachments`: the same `jsonb[]` of
-- `{src,title,type,path}` objects stored in the public `attachments` bucket,
-- so one attachment renderer serves both.
--
create table public.deal_stage_changes (
    id bigint generated by default as identity primary key,
    deal_id bigint not null references public.deals(id) on update cascade on delete cascade,
    -- Null for the first transition of a deal created straight into a
    -- non-default stage: there is no previous stage to name.
    from_stage text,
    to_stage text not null,
    -- Free text, required when the move goes through `move_deal_stage()`, null
    -- when the stage was changed by another path (that gap is the point: an
    -- undocumented move stays visible as one).
    reason text,
    -- Who moved it. Null only when the actor has no `sales` row (service role,
    -- an import), never silently attributed to somebody else.
    sales_id bigint references public.sales(id),
    changed_at timestamp with time zone not null default now(),
    attachments jsonb[],
    constraint deal_stage_changes_to_stage_not_blank check (btrim(to_stage) <> ''),
    constraint deal_stage_changes_stages_differ check (from_stage is distinct from to_stage)
);

-- The deal timeline reads this table newest-first, always for one deal.
create index deal_stage_changes_deal_id_idx
    on public.deal_stage_changes (deal_id, changed_at desc);
create index deal_stage_changes_sales_id_idx
    on public.deal_stage_changes (sales_id);

