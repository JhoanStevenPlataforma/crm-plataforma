-- Task module — attachments and comment reactions (§3.2, §8.2, §17.3).
--
-- Phase 2.3 of docs/proposals/enterprise-task-module.md. Three things:
--
--   1. `task_attachments` — file metadata for both task-level and
--      comment-level files, with the counter and the audit events the rest of
--      the module already gets.
--   2. A private `task-attachments` storage bucket. The Phase 1 hardening
--      (20260803182000) path-scoped task files inside the `attachments`
--      bucket, but that bucket is PUBLIC (see the initial migration), so any
--      object in it is served to anybody holding the URL, signed in or not.
--      Policies on a public bucket gate the API and leave the object path
--      open, so task files move to a bucket that is actually private and are
--      read through short-lived signed URLs.
--   3. A surrogate `id` on `task_comment_reactions`, which shipped with a
--      composite primary key that PostgREST and react-admin cannot address —
--      un-reacting is a delete by id.
--
-- Hand-written rather than `db diff`-generated, and additive on `public.tasks`
-- (it only reads it), so it does not trigger the drop-view cascade that a
-- generated diff produces for every view reading `tasks`.


--
-- 1. Attachments
--

create table "public"."task_attachments" (
    "id" bigint generated by default as identity not null,
    "task_id" bigint not null,
    "comment_id" bigint,
    "storage_path" text not null,
    "file_name" text not null,
    "mime_type" text,
    "size_bytes" bigint,
    "checksum" text,
    "uploaded_by" bigint not null,
    "uploaded_at" timestamp with time zone not null default now(),
    "deleted_at" timestamp with time zone,
    "deleted_by" bigint
);


alter table "public"."task_attachments" enable row level security;

CREATE UNIQUE INDEX task_attachments_pkey ON public.task_attachments USING btree (id);

CREATE INDEX task_attachments_task ON public.task_attachments USING btree (task_id, uploaded_at) WHERE (deleted_at IS NULL);

CREATE INDEX task_attachments_comment ON public.task_attachments USING btree (comment_id, uploaded_at) WHERE ((deleted_at IS NULL) AND (comment_id IS NOT NULL));

CREATE UNIQUE INDEX task_attachments_path_unique ON public.task_attachments USING btree (storage_path) WHERE (deleted_at IS NULL);

