-- Customer portal slides and templates (docs/proposals/quote-portal-presentation.md §7).
--
-- Replaces the portal builder (brand kit, experiences, versions), which never
-- left this machine: admins keep portal TEMPLATES of free-form slides, one of
-- them active; the active one is frozen into `quote_versions.slides` at issue
-- and served to the customer by `quote_portal_document()`. The template the
-- portal always had ships as "Predeterminada", active and locked.
--
