--
-- Help centre: the in-app manual (docs/proposals/help-center.md).
--
-- Two tables (categories, tutorials), their policies and grants, the public
-- `help-media` bucket the recordings are served from, and the first content:
-- the quotation flow, seeded UNPUBLISHED -- a tutorial is published once its
-- recording is attached.
--

--
-- Help centre (the in-app manual)
--
-- Short video tutorials, grouped in categories, that teach one task each. The
-- catalogue is DATA so a tutorial is added, replaced or unpublished from the
-- admin screen, never by a deploy. The files themselves live in the
-- `help-media` bucket; a row only names them, and the three `*_path` checks
-- keep it to names the uploader generated -- a tutorial can never point at an
-- arbitrary address.
create table public.help_categories (
    id          bigint generated by default as identity primary key,
    slug        text not null unique
        check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 80),
    title       text not null check (char_length(btrim(title)) between 1 and 80),
    description text,
    -- The name of an icon the client knows (`help/helpIcons.ts`); an unknown
    -- name renders the default one rather than failing.
    icon        text not null default 'book-open'
        check (icon ~ '^[a-z0-9-]{1,40}$'),
    rank        integer not null default 0,
    created_at  timestamp with time zone not null default now(),
    updated_at  timestamp with time zone not null default now()
);

-- Replacing a video is a NEW file and a new `video_path`, never an overwrite:
-- the files are served with a one-year immutable cache, so a path whose bytes
-- changed would keep playing the old recording for whoever had it cached.
create table public.help_tutorials (
    id               bigint generated by default as identity primary key,
    category_id      bigint not null
        references public.help_categories(id) on delete restrict,
    slug             text not null unique
        check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 120),
    title            text not null check (char_length(btrim(title)) between 1 and 120),
    description      text,
    steps            text[] not null default '{}'::text[],
    video_path       text
        check (video_path ~ '^video/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(mp4|webm)$'),
    poster_path      text
        check (poster_path ~ '^poster/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(webp|jpg|png)$'),
    captions_path    text
        check (captions_path ~ '^captions/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.vtt$'),
    duration_seconds integer check (duration_seconds >= 0),
    rank             integer not null default 0,
    is_published     boolean not null default false,
    created_at       timestamp with time zone not null default now(),
    updated_at       timestamp with time zone not null default now(),
    -- A published card with nothing to play is a dead end for the reader.
    constraint help_tutorials_published_has_video
        check (not is_published or video_path is not null)
);

create index help_tutorials_category_rank
    on public.help_tutorials (category_id, rank);

--
-- Help centre: "updated on" is what the reader is shown, so the server keeps it.
--
create or replace trigger help_categories_set_updated_at
    before update on public.help_categories
    for each row execute function public.set_updated_at();

create or replace trigger help_tutorials_set_updated_at
    before update on public.help_tutorials
    for each row execute function public.set_updated_at();

--
-- Help centre: everyone signed in reads the manual, only admins write it. A
-- tutorial that is not published is a draft only admins see, so a recording
-- can be prepared and checked before anybody is sent to it.
--
alter table public.help_categories enable row level security;

create policy "Help categories are readable by authenticated users"
    on public.help_categories for select to authenticated
    using (true);

create policy "Help categories can be added by admins"
    on public.help_categories for insert to authenticated
    with check ((select public.is_admin()));

create policy "Help categories can be updated by admins"
    on public.help_categories for update to authenticated
    using ((select public.is_admin()))
    with check ((select public.is_admin()));

create policy "Help categories can be deleted by admins"
    on public.help_categories for delete to authenticated
    using ((select public.is_admin()));

alter table public.help_tutorials enable row level security;

create policy "Published help tutorials are readable by authenticated users"
    on public.help_tutorials for select to authenticated
    using (is_published or (select public.is_admin()));

create policy "Help tutorials can be added by admins"
    on public.help_tutorials for insert to authenticated
    with check ((select public.is_admin()));

create policy "Help tutorials can be updated by admins"
    on public.help_tutorials for update to authenticated
    using ((select public.is_admin()))
    with check ((select public.is_admin()));

create policy "Help tutorials can be deleted by admins"
    on public.help_tutorials for delete to authenticated
    using ((select public.is_admin()));

--
-- Help centre. No `anon` grant: the manual is for people signed in.
--
revoke all on table public.help_categories from anon, authenticated;
grant select, insert, update, delete on table public.help_categories to authenticated;
grant all on table public.help_categories to service_role;
revoke all on sequence public.help_categories_id_seq from anon, authenticated;
grant usage on sequence public.help_categories_id_seq to authenticated;
grant all on sequence public.help_categories_id_seq to service_role;

revoke all on table public.help_tutorials from anon, authenticated;
grant select, insert, update, delete on table public.help_tutorials to authenticated;
grant all on table public.help_tutorials to service_role;
revoke all on sequence public.help_tutorials_id_seq from anon, authenticated;
grant usage on sequence public.help_tutorials_id_seq to authenticated;
grant all on sequence public.help_tutorials_id_seq to service_role;

--
-- The bucket, with its limits on the bucket itself: 50 MB (the project's
-- global ceiling; a tutorial is a few MB), recordings, posters and captions
-- only.
--
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('help-media', 'help-media', true, 52428800,
        array['video/mp4', 'video/webm',
              'image/webp', 'image/jpeg', 'image/png',
              'text/vtt'])
on conflict (id) do nothing;

drop policy if exists "Help media can be uploaded by admins" on storage.objects;

-- Help centre media. A PUBLIC bucket (`help-media`, created with its size and
-- type limits by the migration), and deliberately so: a tutorial is a screen
-- recording of made-up data, and a stable address is what lets the browser
-- seek with range requests, cache the file for a year and, later, be served
-- from a CDN by changing one variable. NEVER record a tutorial over real
-- customer data -- nothing here would protect it. What needs a session is the
-- catalogue (`help_tutorials`), not the files. Paths are
-- `<video|poster|captions>/<uuid>.<ext>` and never overwritten (no update
-- policy): a replaced recording is a new file, the old one stays as the way
-- back.
create policy "Help media can be uploaded by admins"
    on storage.objects for insert to authenticated
    with check (
        bucket_id = 'help-media'
        and (select public.is_admin())
        and name ~ '^(video/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(mp4|webm)|poster/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(webp|jpg|png)|captions/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.vtt)$'
    );

