-- applies verbatim, and `nb_*` counters are exactly the shape it was measured
-- on. Keep them that way.
create or replace view public.quotes_summary with (security_invoker = on) as
select
    q.id,
    q.quote_number,
    q.title,
    q.deal_id,
    q.company_id,
    q.contact_id,
    q.sales_id,
    q.price_list_id,
    q.currency,
    q.status_key,
    q.valid_until,
    q.terms,
