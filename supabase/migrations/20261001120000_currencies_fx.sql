-- Backfill, before the constraints: a version in the base currency gets rate
-- 1; one in another currency gets NOTHING. No rate is invented for a document
-- already sent -- its equivalent stays unknown, which is the truth.
do $$
begin
    perform set_config('app.quote_purge', 'on', true);

    update public.quote_versions v
       set base_currency       = 'COP',
           exchange_rate       = case when v.currency = 'COP' then 1 end,
           rate_kind           = case when v.currency = 'COP' then 'base'::public.quote_rate_kind end,
           rate_effective_date = case when v.currency = 'COP' then coalesce(v.issued_at, v.created_at)::date end,
           subtotal_base       = case when v.currency = 'COP' then v.subtotal end,
           discount_total_base = case when v.currency = 'COP' then v.discount_total end,
           tax_total_base      = case when v.currency = 'COP' then v.tax_total end,
           total_base          = case when v.currency = 'COP' then v.total end;

    perform set_config('app.quote_purge', '', true);
end;
$$;

