--
-- Currencies & exchange rates (docs/proposals/multi-currency-fx.md).
--
-- Hand-written, like every quote-module migration: `supabase db diff` emits a
-- destructive drift migration on this stack. The declarative copy of every
-- object below lives in `supabase/schemas/0{1..6}_*.sql`.
--
-- THE RATE CONVENTION, used by every table and function here:
--
--     rate = units of the BASE currency per ONE unit of the currency
--
-- With COP as the base, USD at 4000 means 1 USD = 4000 COP. Converting an
-- amount from X to Y is `amount * rate_X / rate_Y`; the base itself has rate 1.
--

--
-- Enums
--
create type public.fx_rate_kind as enum ('official', 'commercial');
create type public.quote_rate_kind as enum ('base', 'official', 'commercial', 'custom');

--
-- Catalogue of currencies
--
create table public.currencies (
    code             character(3) primary key check (code ~ '^[A-Z]{3}$'),
    name             text not null check (btrim(name) <> ''),
    symbol           text not null default '',
    -- How many decimals the currency is SHOWN and converted with. Amounts are
    -- stored with two decimals whatever this says (numeric(14,2) and the
    -- generated line columns): a converted price is rounded to
    -- least(decimals, 2), so a currency with 0 stores whole units.
    decimals         smallint not null default 2 check (decimals between 0 and 4),
    is_active        boolean not null default true,
    -- The company's base currency: what every rate is expressed in and what a
    -- deal's amount is counted in. Switched only by `set_base_currency()`.
    is_base          boolean not null default false,
    -- Pre-selected when a quotation is created.
    is_quote_default boolean not null default false,
    created_at       timestamp with time zone not null default now(),
    updated_at       timestamp with time zone not null default now(),
    constraint currencies_base_is_active check (not is_base or is_active),
    constraint currencies_quote_default_is_active check (not is_quote_default or is_active)
);

create unique index currencies_one_base on public.currencies ((true)) where is_base;
create unique index currencies_one_quote_default on public.currencies ((true)) where is_quote_default;

--
-- Rate providers
--
-- One row per implementation in `supabase/functions/exchange-rates-sync/providers/`.
-- Rows are migration-authored (a provider with no code behind it is a button
-- that does nothing), so clients may update the tunables but never insert.
--
create table public.exchange_rate_providers (
    id                       bigint generated by default as identity primary key,
    key                      text not null unique check (key ~ '^[a-z][a-z0-9_]*$'),
    name                     text not null,
    description              text,
    is_enabled               boolean not null default true,
    -- Lower runs first and wins a tie between two official rates of one day.
    -- The cross-rate provider must run after the one it pivots on.
    priority                 smallint not null default 100,
    requires_credentials     boolean not null default false,
    refresh_interval_minutes integer not null default 360
        check (refresh_interval_minutes between 15 and 10080),
    -- The currencies this provider is asked for.
    currencies               character(3)[] not null default '{}',
    -- A Supabase Vault secret id, never the secret. Written by
    -- `set_fx_provider_secret()` only.
    credentials_secret_id    uuid,
    -- System columns, written by the sync functions only.
    last_attempt_at          timestamp with time zone,
    last_success_at          timestamp with time zone,
    last_error_at            timestamp with time zone,
    last_error               text,
    consecutive_failures     integer not null default 0,
    created_at               timestamp with time zone not null default now(),
    updated_at               timestamp with time zone not null default now()
);

--
-- Rates
--
-- APPEND-ONLY. A rate somebody acted on is evidence; a correction is a new
-- row (`supersedes_id`), never an edit. A manual rate never overwrites the
-- provider's: they are different rows, and `kind` keeps the official rate and
-- the company's commercial rate apart.
--
create table public.exchange_rates (
    id                 bigint generated by default as identity primary key,
    currency_code      character(3) not null references public.currencies(code),
    base_currency_code character(3) not null references public.currencies(code),
    rate               numeric(20,10) not null check (rate > 0),
    kind               public.fx_rate_kind not null,
    -- Null for a rate typed by a person.
    provider_id        bigint references public.exchange_rate_providers(id),
    -- The day the rate applies from, as the SOURCE states it -- never the day
    -- we fetched it.
    effective_date     date not null,
    -- Official: the last day the source says it applies (the TRM covers a
    -- weekend in one row). Commercial: the company's own expiry; past it the
    -- official rate applies again.
    valid_until        date,
    fetched_at         timestamp with time zone not null default now(),
    -- The pivot of a cross rate (EUR via USD), null for a direct one.
    derived_via        character(3) references public.currencies(code),
    source_payload     jsonb,
    created_by         bigint references public.sales(id),
    note               text,
    supersedes_id      bigint references public.exchange_rates(id),
    created_at         timestamp with time zone not null default now(),
    constraint exchange_rates_not_base check (currency_code <> base_currency_code),
    constraint exchange_rates_provider_is_official
        check (provider_id is null or kind = 'official'),
    constraint exchange_rates_has_origin
        check (provider_id is not null or created_by is not null),
    constraint exchange_rates_manual_note
        check (provider_id is not null or nullif(btrim(note), '') is not null),
    constraint exchange_rates_validity
        check (valid_until is null or valid_until >= effective_date),
    constraint exchange_rates_derived_from_provider
        check (derived_via is null or provider_id is not null)
);

-- One row per currency, provider and day: a replayed sync is a no-op.
create unique index exchange_rates_provider_day
    on public.exchange_rates (currency_code, base_currency_code, provider_id, effective_date)
    where provider_id is not null;

-- "The rate of X on day D", which every resolution asks.
create index exchange_rates_lookup
    on public.exchange_rates (currency_code, kind, effective_date desc, id desc);

create index exchange_rates_history
    on public.exchange_rates (effective_date desc, id desc);

--
-- Settings (singleton)
--
create table public.exchange_rate_settings (
    id                                integer primary key default 1 check (id = 1),
    -- Which rate a new draft quotation starts from. 'commercial' falls back to
    -- the official rate when the company has set none.
    quote_rate_kind_default           public.fx_rate_kind not null default 'commercial',
    -- An official rate older than this many days (and past its own
    -- `valid_until`) is reported stale and refused at issue. Three covers a
    -- weekend for sources that publish on business days only.
    stale_after_days                  smallint not null default 3
        check (stale_after_days between 0 and 30),
    -- How far from the official rate a REP may set a custom one. 0 = never.
    rep_custom_rate_tolerance_percent numeric(5,2) not null default 0
        check (rep_custom_rate_tolerance_percent between 0 and 100),
    -- Consecutive failed runs of one provider before the admins are told.
    failure_alert_threshold           smallint not null default 3
        check (failure_alert_threshold between 1 and 50),
    updated_at                        timestamp with time zone not null default now()
);

--
-- Sync runs: one row per attempt to call a provider
--
create table public.exchange_rate_sync_runs (
    id                    bigint generated by default as identity primary key,
    provider_id           bigint not null references public.exchange_rate_providers(id),
    triggered_by          text not null check (triggered_by in ('cron', 'manual', 'backfill')),
    triggered_by_sales_id bigint references public.sales(id),
    status                text not null default 'running'
        check (status in ('running', 'succeeded', 'failed')),
    started_at            timestamp with time zone not null default now(),
    finished_at           timestamp with time zone,
    attempts              smallint not null default 0,
    rates_received        integer not null default 0,
    rates_inserted        integer not null default 0,
    rates_rejected        integer not null default 0,
    error                 text,
    details               jsonb,
    constraint exchange_rate_sync_runs_finished
        check ((status = 'running') = (finished_at is null))
);

-- The lock: two runs of one provider at once is a unique violation, not a race.
create unique index exchange_rate_sync_runs_one_running
    on public.exchange_rate_sync_runs (provider_id)
    where status = 'running';

create index exchange_rate_sync_runs_provider
    on public.exchange_rate_sync_runs (provider_id, started_at desc);

