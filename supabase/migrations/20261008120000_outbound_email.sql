--
-- The scheduled dispatch. Every minute, and a no-op while nothing is due or
-- while the two Vault secrets (`email_dispatch_url`,
-- `email_dispatch_service_key`) do not exist -- see the proposal's "Setup".
-- A message is normally sent by its sender's own request the moment it is
-- queued; this tick is what retries a transient failure and what notices a
-- dispatcher that never reported back. Not in `supabase/schemas/` (a row in
-- `cron.job` is cluster state); the function is, in 02_functions.sql.
--
do $$
begin
    create extension if not exists pg_cron;

    perform cron.unschedule('email-dispatch')
      where exists (select 1 from cron.job where jobname = 'email-dispatch');
    perform cron.schedule(
        'email-dispatch',
        '* * * * *',
        $cron$select public.email_dispatch_tick();$cron$);
exception
    when others then
        raise warning
            'pg_cron unavailable (%): a failed email is retried only by hand',
            sqlerrm;
end;
$$;
