--
-- Outbound email, phase 1 (docs/proposals/outbound-email.md).
--
-- Mail to customers, sent from a record and, first of all, the link to an
-- issued quotation: the settings (one row, credentials in Vault), reusable
-- templates, the message outbox that is also the history, the functions that
-- queue, claim and settle a message, and the message on the timeline.
--
-- Applying this sends nothing: the provider is `mock` until an administrator
-- chooses another, and a message it handles ends `simulated`.
--

--
-- Outbound email (docs/proposals/outbound-email.md)
--
-- Mail the CRM sends to a CUSTOMER: a message a user wrote from a record, and
-- first of all the link to an issued quotation. `task_notifications` is not
-- reused for it on purpose -- its recipient is a `sales` row, and quiet hours
-- or a digest make no sense for a customer -- and stays what it is: the outbox
-- of notifications to the team.
--

-- The one definition of "an address we will send to", used by the table
-- checks below and by every function that takes a recipient. Deliberately
-- narrower than the RFC: no quoted local part, no comment, no whitespace and
-- no control character, so an address can never smuggle a second header.
-- Defined here, before the tables whose checks call it.
create or replace function public.is_valid_email(p_email text) returns boolean
    language sql immutable
    set search_path to ''
as $$
    select p_email is not null
       and char_length(p_email) between 3 and 320
       and p_email ~ '^[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$';
$$;

-- The one row of settings. No credential lives here: `credentials_secret_id`
-- and `webhook_secret_id` name a Supabase Vault secret, written only by
-- `set_email_provider_secret()`.
--
-- `provider_key = 'mock'` is the default and sends NOTHING: a message handled
-- by it ends `simulated`, never `accepted`, so no screen can claim a mail that
-- did not leave.
create table public.email_settings (
    id                    smallint primary key default 1 check (id = 1),
    provider_key          text not null default 'mock'
        check (provider_key in ('mock', 'postmark')),
    is_enabled            boolean not null default true,
    from_email            extensions.citext
        check (from_email is null or public.is_valid_email(from_email::text)),
    from_name             text
        check (from_name is null
               or (char_length(from_name) <= 120 and from_name !~ '[[:cntrl:]"<>]')),
    -- 'sender': replies go to the user who wrote the message. 'none': to the
    -- shared address.
    reply_to_mode         text not null default 'sender'
        check (reply_to_mode in ('sender', 'none')),
    -- Postmark message streams: what tells a one-to-one message from a
    -- commercial follow-up, with its own reputation and unsubscribe rules.
    transactional_stream  text not null default 'outbound'
        check (transactional_stream ~ '^[a-z0-9-]{1,60}$'),
    commercial_stream     text not null default 'broadcast'
        check (commercial_stream ~ '^[a-z0-9-]{1,60}$'),
    credentials_secret_id uuid,
    webhook_secret_id     uuid,
    max_per_user_hour     integer not null default 60
        check (max_per_user_hour between 1 and 1000),
    max_per_recipient_day integer not null default 5
        check (max_per_recipient_day between 1 and 100),
    updated_at            timestamp with time zone not null default now(),
    updated_by            bigint references public.sales(id) on delete set null
);

-- Reusable messages. `{{variable}}` is the only syntax; which variables a
-- template may name depends on its scope (`email_template_variables()`), and a
-- template naming another one is refused when saved.
--
-- The body is PLAIN TEXT. The server escapes it into the branded layout, so a
-- template cannot carry markup, and neither can a value interpolated into it.
create table public.email_templates (
    id         bigint generated by default as identity primary key,
    key        text not null
        check (key ~ '^[a-z0-9]+(_[a-z0-9]+)*$' and char_length(key) <= 60),
    name       text not null check (char_length(btrim(name)) between 1 and 120),
    subject    text not null
        check (char_length(btrim(subject)) between 1 and 200
               and subject !~ '[[:cntrl:]]'),
    body       text not null check (char_length(btrim(body)) between 1 and 20000),
    scope      text not null default 'generic'
        check (scope in ('generic', 'contact', 'lead', 'company', 'deal', 'quote')),
    -- 'transactional': an answer to something the customer asked for (their
    -- quotation). 'commercial': anything we initiate to sell.
    category   text not null default 'transactional'
        check (category in ('transactional', 'commercial')),
    language   text not null default 'es' check (language in ('es', 'en', 'fr')),
    is_active  boolean not null default true,
    -- Seeded templates can be reworded, never deleted or re-keyed: an
    -- automation names them by key.
    is_system  boolean not null default false,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint email_templates_key_language unique (key, language)
);

-- One row per message: the outbox while it waits, the history afterwards.
--
-- What was written is FROZEN at insert (`email_messages_guard`): the subject,
-- the text, the recipient and, for a quotation, the exact version shared. A
-- later revision of the quote changes none of it.
--
-- The customer link is NOT stored: `body_text` carries the `{{quote_link}}`
-- marker and the dispatcher resolves it while sending, so a token never sits
-- in this table, in a log or in an error.
--
-- `delivered` is written by the provider's webhook alone. The provider's API
-- accepting a message proves nothing about the mailbox: that is `accepted`.
create table public.email_messages (
    id                  bigint generated by default as identity primary key,
    created_at          timestamp with time zone not null default now(),
    -- Who sent it. Null only for an automation.
    sales_id            bigint references public.sales(id),
    origin              text not null default 'manual'
        check (origin in ('manual', 'automation', 'test')),
    automation_key      text,
    category            text not null default 'transactional'
        check (category in ('transactional', 'commercial')),
    language            text not null default 'es' check (language in ('es', 'en', 'fr')),
    to_email            extensions.citext not null
        check (public.is_valid_email(to_email::text)),
    to_name             text
        check (to_name is null
               or (char_length(to_name) <= 120 and to_name !~ '[[:cntrl:]"<>]')),
    contact_id          bigint references public.contacts(id) on delete set null,
    subject             text not null
        check (char_length(btrim(subject)) between 1 and 200
               and subject !~ '[[:cntrl:]]'),
    body_text           text not null
        check (char_length(btrim(body_text)) between 1 and 20000),
    template_id         bigint references public.email_templates(id) on delete set null,
    template_key        text,
    -- What the layout prints beside the text (quote number, total, currency,
    -- sender), read once from the frozen version. Never a token.
    variables           jsonb not null default '{}'::jsonb
        check (jsonb_typeof(variables) = 'object'),
    entity_type         public.task_entity,
    entity_id           bigint,
    quote_id            bigint references public.quotes(id) on delete cascade,
    quote_version_id    bigint references public.quote_versions(id) on delete cascade,
    status              text not null default 'pending'
        check (status in ('pending', 'processing', 'accepted', 'delivered',
                          'bounced', 'failed', 'canceled', 'simulated')),
    attempt             smallint not null default 0,
    scheduled_for       timestamp with time zone not null default now(),
    claimed_at          timestamp with time zone,
    provider_key        text,
    provider_message_id text,
    -- A stable key the UI translates, and a short technical message. Never a
    -- request body, a header or a credential.
    error_code          text,
    error               text,
    accepted_at         timestamp with time zone,
    delivered_at        timestamp with time zone,
    bounced_at          timestamp with time zone,
    failed_at           timestamp with time zone,
    -- One per press of "Send": repeating the call returns this row.
    idempotency_key     uuid not null unique,
    -- "This automation, this version, this step, once."
    dedupe_key          text unique,
    constraint email_messages_entity
        check ((entity_type is null) = (entity_id is null)),
    constraint email_messages_quote
        check ((quote_version_id is null and quote_id is null)
               or (quote_version_id is not null and quote_id is not null
                   and entity_type = 'quote' and entity_id = quote_id)),
    constraint email_messages_origin
        check ((origin = 'automation') = (automation_key is not null)
               and (origin = 'automation' or sales_id is not null))
);

create index email_messages_outbox
    on public.email_messages (scheduled_for)
    where status in ('pending', 'processing');
create index email_messages_entity_idx
    on public.email_messages (entity_type, entity_id, created_at desc);
create index email_messages_contact_idx
    on public.email_messages (contact_id, created_at desc)
    where contact_id is not null;
create index email_messages_sender_idx
    on public.email_messages (sales_id, created_at desc);
create index email_messages_recipient_idx
    on public.email_messages (to_email, created_at desc);
create index email_messages_provider_idx
    on public.email_messages (provider_key, provider_message_id)
    where provider_message_id is not null;

