--
-- Task module — Phase 1, step 1: enums and catalogues.
--
-- Implements proposal §3.3 (DDL) + Appendix C step 1:
--
--   - `task_statuses`: the 9 lifecycle states (§4.1). `key` is the machine
--     value the state machine and the UI work with; `label` is the default
--     display text (the frontend translates by `key` through i18n).
--   - `task_priorities`: low / normal / high / urgent, with a display rank
--     and an optional SLA in hours.
--   - `task_types`: replaces the free-text `type` column (fixes W11). Seeded
--     from the defaults in `root/defaultConfiguration.ts` plus whatever the
--     current `tasks.type` values contain, so no existing data is orphaned.
--
-- The enums (`task_role`, `task_entity`, `task_event_type`) are declared here
-- as well because the subsequent migrations reference them; Postgres enum
-- values cannot be added inside a transaction, so each migration that uses a
-- new value must be in its own file.
--

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------

create type public.task_role as enum ('owner', 'collaborator', 'watcher', 'team');

