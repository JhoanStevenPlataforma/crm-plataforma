-- Adopt any legacy `type` values that are not in the default set, so the
-- existing rows keep their type after the migration (Appendix C step 1).
insert into public.task_types (key, label, icon, is_active)
select distinct coalesce(nullif(type, ''), 'none'), initcap(coalesce(nullif(type, ''), 'none')), null, true
from public.tasks
where coalesce(nullif(type, ''), 'none') not in
      ('none', 'email', 'demo', 'lunch', 'meeting', 'follow-up', 'thank-you', 'ship', 'call');

-- ---------------------------------------------------------------------------
-- RLS and grants
-- ---------------------------------------------------------------------------

-- Catalogues are shared reference data: readable by every authenticated user,
-- writable only by admins (`task.manage_catalogs` capability, §17.1).
alter table public.task_statuses enable row level security;
alter table public.task_priorities enable row level security;
alter table public.task_types enable row level security;

create policy "Catalogues are readable by every authenticated user"
    on public.task_statuses for select to authenticated
    using (true);
create policy "Catalogues are manageable by admins only"
    on public.task_statuses for all to authenticated
    using (public.is_admin())
    with check (public.is_admin());

create policy "Catalogues are readable by every authenticated user"
    on public.task_priorities for select to authenticated
    using (true);
create policy "Catalogues are manageable by admins only"
    on public.task_priorities for all to authenticated
    using (public.is_admin())
    with check (public.is_admin());

create policy "Catalogues are readable by every authenticated user"
    on public.task_types for select to authenticated
    using (true);
create policy "Catalogues are manageable by admins only"
    on public.task_types for all to authenticated
    using (public.is_admin())
    with check (public.is_admin());

-- Following the existing pattern (`grant all ... to anon/authenticated/...`),
-- but scoped to authenticated for the task tables (§17.3 P1: grant only what
-- PostgREST needs, to `authenticated`).
grant select, insert, update, delete on table public.task_statuses to authenticated;
grant select, insert, update, delete on table public.task_priorities to authenticated;
grant select, insert, update, delete on table public.task_types to authenticated;
grant select, insert, update, delete on table public.task_statuses to service_role;
grant select, insert, update, delete on table public.task_priorities to service_role;
grant select, insert, update, delete on table public.task_types to service_role;
