--
-- BOTH summary views were dropped above so the column could be added: they
-- read `public.tasks`, so Postgres refuses the ALTER while they exist.
-- `contacts_summary.nb_tasks` is why the contact list depends on it at all.
-- Recreate both unchanged, with their grants — dropping a view without
-- restoring it takes the whole list page down with a schema-cache miss.
--
create or replace view public.contacts_summary with (security_invoker = on) as
select
    co.id,
    co.first_name,
    co.last_name,
    co.gender,
    co.title,
    co.background,
    co.avatar,
    co.first_seen,
    co.last_seen,
    co.has_newsletter,
    co.status,
    co.tags,
    co.company_id,
    co.sales_id,
    co.linkedin_url,
    co.email_jsonb,
    co.phone_jsonb,
    (jsonb_path_query_array(co.email_jsonb, '$[*]."email"'))::text as email_fts,
    (jsonb_path_query_array(co.phone_jsonb, '$[*]."number"'))::text as phone_fts,
    c.name as company_name,
    -- Same rewrite as companies_summary: the previous join + GROUP BY over
    -- tasks aggregated all 200k contacts before the LIMIT (~1.1 s per page for
    -- a manager). As a subquery, page 1 costs well under a millisecond.
    -- Soft-deleted tasks do not count as open work.
    (select count(*) from public.tasks t
      where t.contact_id = co.id
        and t.done_date is null
        and t.deleted_at is null) as nb_tasks
from public.contacts co
    left join public.companies c on co.company_id = c.id;

--
-- The list/detail projection of a task (proposal §3.4, §15).
--
-- Every task list has to render a status chip, a priority badge, a type icon
-- and the record the task hangs off. Resolving those from the client would be
