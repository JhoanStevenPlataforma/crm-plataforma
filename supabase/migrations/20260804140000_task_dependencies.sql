-- Task module — dependencies, auto-unblock and the blocked clock (§10).
--
-- Phase 2.6 of docs/proposals/enterprise-task-module.md. Also closes the
-- Phase 1 gap where tasks.blocked_seconds existed but never moved: the
-- trigger deferred the arithmetic to a scheduled job that was never written.
-- Recording blocked_since makes the duration exact with no job at all.

create type "public"."task_dependency_kind" as enum ('blocks', 'parent', 'related', 'duplicates');

