  create policy "Dependencies are closed by users who can see either end"
  on "public"."task_dependencies"
  as permissive
  for update
  to authenticated
using ((public.can_see_task(source_task_id) OR public.can_see_task(target_task_id)))
with check ((public.can_see_task(source_task_id) OR public.can_see_task(target_task_id)));



  create policy "Dependencies are created by users who can see both ends"
  on "public"."task_dependencies"
  as permissive
  for insert
  to authenticated
with check ((public.can_see_task(source_task_id) AND public.can_see_task(target_task_id)));



  create policy "Dependencies are readable from either end"
  on "public"."task_dependencies"
  as permissive
  for select
  to authenticated
using ((public.can_see_task(source_task_id) OR public.can_see_task(target_task_id)));


