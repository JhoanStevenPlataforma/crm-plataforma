CREATE TRIGGER task_dependencies_audit AFTER INSERT OR UPDATE ON public.task_dependencies FOR EACH ROW EXECUTE FUNCTION public.task_dependencies_audit();

CREATE TRIGGER task_dependencies_before_insert BEFORE INSERT ON public.task_dependencies FOR EACH ROW EXECUTE FUNCTION public.task_dependencies_before_insert();

CREATE TRIGGER task_dependencies_no_cycle BEFORE INSERT OR UPDATE ON public.task_dependencies FOR EACH ROW EXECUTE FUNCTION public.assert_no_dependency_cycle();

CREATE TRIGGER tasks_unblock_dependents AFTER UPDATE ON public.tasks FOR EACH ROW WHEN ((old.status_id IS DISTINCT FROM new.status_id)) EXECUTE FUNCTION public.tasks_unblock_dependents();


